#[cfg(test)]
mod tests {
    use super::*;
    use crate::scan::scan;

    #[test]
    fn every_rule_is_complete() {
        assert!(!RULES.is_empty());
        for r in RULES {
            assert!(!r.avoid.is_empty(), "{r:?}");
            assert!(!r.write.is_empty(), "{r:?}");
            assert!(!matches!(r.note, Some(s) if s.trim().is_empty()), "{r:?}");
            assert!(!r.bad.is_empty(), "{r:?}");
            assert!(!r.good.is_empty(), "{r:?}");
            for a in r.avoid {
                assert!(!a.is_empty(), "{r:?}");
            }
            for k in r.keep {
                assert!(
                    r.avoid.iter().any(|a| k.contains(a)),
                    "keep {k:?} は avoid のどれも含まないので意味が無い"
                );
            }
        }
    }

    #[test]
    fn avoid_strings_are_unique_across_rules() {
        let mut seen = std::collections::HashSet::new();
        for r in RULES {
            for a in r.avoid {
                assert!(seen.insert(*a), "{a:?} が 2 つの規則にある");
            }
        }
    }

    #[test]
    fn bad_examples_hit_their_own_rule_and_good_examples_do_not() {
        for r in RULES {
            for b in r.bad {
                let hits = scan(b, std::slice::from_ref(r));
                assert!(
                    !hits.is_empty(),
                    "bad {b:?} は規則 {:?} に当たるべき",
                    r.avoid
                );
            }
            for g in r.good {
                let hits = scan(g, std::slice::from_ref(r));
                assert!(
                    hits.is_empty(),
                    "good {g:?} は規則 {:?} に当たってはいけない: {hits:?}",
                    r.avoid
                );
            }
        }
    }

    #[test]
    fn render_line_shows_avoid_write_keep_and_note() {
        let line = RULES[0].render_line();
        assert!(line.starts_with("道具が言 / 道具は言 -> 実行時にツール側から案内する"));
        assert!(line.contains("keep: 道具が言語 / 道具は言語"));
        assert!(line.contains("note: "));
        assert!(!line.contains('\n'));
        assert!(RULES[1].render_line().contains("keep: -"));
    }

    /// ある規則の avoid が別の規則の avoid を含むとき (`停止窓` と `窓`、`退役` を含む語など)、長い方の
    /// 字面だけを書いた文書には長い方の規則 1 件だけが出る。
    #[test]
    fn a_longer_avoid_containing_a_shorter_one_reports_only_the_longer_rule() {
        let mut pairs = 0;
        for (i, long) in RULES.iter().enumerate() {
            for a in long.avoid {
                let contains_shorter = RULES.iter().enumerate().any(|(j, short)| {
                    j != i
                        && short
                            .avoid
                            .iter()
                            .any(|b| b.len() < a.len() && a.contains(b))
                });
                if !contains_shorter {
                    continue;
                }
                pairs += 1;
                let hits = scan(&format!("{a}\n"), RULES);
                assert_eq!(hits.len(), 1, "{a:?}: {hits:?}");
                assert!(std::ptr::eq(hits[0].rule, long), "{a:?}: {hits:?}");
            }
        }
        assert!(
            pairs >= 2,
            "停止窓 と 無窓 は 窓 を含むので、包含の組は 2 つ以上ある"
        );
    }

    /// 比喩の「脚」を避ける規則を足す前からあった、`脚` を含む長い avoid (`旧7脚`、`合成脚` など) は、
    /// 文中に現れても長い方の規則 1 件だけが出る。
    #[test]
    fn older_avoids_containing_leg_report_only_their_own_rule() {
        let leg = RULES
            .iter()
            .find(|r| r.avoid == ["脚"])
            .expect("脚 の規則がある");
        let longer = [
            "旧7脚",
            "実7脚",
            "合成脚",
            "page 脚",
            "蒸留脚",
            "同条件の脚",
            "脚関数",
        ];
        for a in longer {
            let owner = RULES
                .iter()
                .find(|r| r.avoid.contains(&a))
                .unwrap_or_else(|| panic!("{a:?} の規則がある"));
            let hits = scan(&format!("ここで{a}を見る。\n"), RULES);
            assert_eq!(hits.len(), 1, "{a:?}: {hits:?}");
            assert!(std::ptr::eq(hits[0].rule, owner), "{a:?}: {hits:?}");
            assert!(!std::ptr::eq(hits[0].rule, leg), "{a:?}: {hits:?}");
        }
    }
}
