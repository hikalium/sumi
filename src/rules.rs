//! 規則の静的な表。パターンは字面のリテラルと `keep` だけで表す。
//!
//! 語句の禁止規則は、候補を対象の文書群で検索し、偽陽性が 0 であることを
//! 検証してから載せる。留保の規則は、文脈に沿って見直すシグナルとして修正案を出す。`bad` は検出を期待する例文、`good` は検出結果が空になるべき例文で、どちらも
//! `cargo test` が検証する。

/// 1 つの規則。
#[derive(Debug, PartialEq, Eq)]
pub struct Rule {
    /// 避ける書き方。どれか 1 つが字面で現れたらヒット
    pub avoid: &'static [&'static str],
    /// 代わりに書く表現の案。機械置換の対象ではなく、書き直す側への案
    pub write: &'static [&'static str],
    /// avoid の文字列を含んでいても別の語なのでヒットにしない書き方
    pub keep: &'static [&'static str],
    /// なぜ避けるか
    pub note: Option<&'static str>,
    /// 当たるべき例文
    pub bad: &'static [&'static str],
    /// 検出結果が空になるべき例文
    pub good: &'static [&'static str],
}

impl Rule {
    /// `--rules` の 1 行。avoid、write、keep、note が読める形。note の改行は空白に潰す。
    pub fn render_line(&self) -> String {
        let keep = if self.keep.is_empty() {
            "-".to_string()
        } else {
            self.keep.join(" / ")
        };
        let note = match self.note {
            Some(n) => n.split('\n').map(str::trim).collect::<Vec<_>>().join(" "),
            None => "-".to_string(),
        };
        format!(
            "{} -> {} | keep: {} | note: {}",
            self.avoid.join(" / "),
            self.write.join(" / "),
            keep,
            note.trim()
        )
    }
}

/// 提案や留保の文を残す必要があるか、変更提案の中で判断を促す。
macro_rules! with_purpose_check {
    ($write:literal) => {
        concat!(
            $write,
            "。そもそもこの文が文章の目的に照らして必須かどうかを判断し、そうでないなら削除することも検討しなさい。"
        )
    };
}
pub(crate) use with_purpose_check;

/// LLM が集めた規則の形。keep は無く、write ・bad ・good は 1 つずつ。avoid は判定した字面のまま。
macro_rules! mined {
    ($avoid:literal, $write:literal, $note:literal, $bad:literal, $good:literal) => {
        Rule {
            avoid: &[$avoid],
            write: &[$write],
            keep: &[],
            note: Some($note),
            bad: &[$bad],
            good: &[$good],
        }
    };
}

